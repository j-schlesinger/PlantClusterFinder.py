def generate_gene_location(
    gene_location_filename: Path,
    dna_unmasked_ok: bool,
    conversion: Conversion,
    remove_non_protein_locations: bool,
    gene_to_mcl_map,
) -> GeneLoc:
    """Generate GeneLoc object from source files.

    Uses glof file, conversion object, and gene to MCL map to create a basic
    GeneLoc object.

    Args:
        gene_location_filename: Location of the GLOF file (generated by parse_input).
        dna_unmasked_ok: True if unmasked DNA is okay.
        conversion: Conversion object from gtpf file.
        remove_non_protein_locations: remove non-protein genes from GeneLoc.
        gene_to_mcl_map: mapping between genes and MCL.

    Returns:
        Basic GeneLoc object for the organism.

    """
    log = logging.getLogger(__name__)
    gene_location = GeneLoc(file_path=gene_location_filename, unmasked=dna_unmasked_ok)
    log.debug("Gene Location File Attributes:")
    for i, attribute in enumerate(gene_location.columns):
        log.debug("Attribute %d: %s", i, attribute)

    # Remove protein or transcript information
    log.debug("Remove transcript information")
    gene_location.add_conversion_columns(
        conversion,
    )
    # Consolidate gene information (one entry per gene)
    log.debug("Consolidate gene information")
    _ = gene_location.consolidate_gene_info()
    # Sort genes according to their physical position on the chromosomes
    log.debug("Sort genes on the chromosomes")
    gene_location.sort_genes()

    # If chosen, remove gene position information about genes that are
    # not present in the protein FASTA file.
    if remove_non_protein_locations:
        log.debug("Remove non-protein coding genes in gene locations.")
        _ = gene_location.remove_non_protein_fasta_gene_locations(
            conversion,
            gene_to_mcl_map.Protein_IDs,
        )
    return gene_location


def get_hypothetical_minimum_gene_length(
    gene_location: GeneLoc, hypothetical_gene_percentile: float
) -> int:
    """Get minimum hypothetical gene length.

    Args:
        gene_location: A basic GeneLoc object.
        hypothetical_gene_percentile: percentile of gene size on which to base result

    Returns:
        Minimum hypothetical gene length in BP.

    """
    log = logging.getLogger(__name__)
    log.debug("Regions where gene gap(?) exceeds %f percentile.", hypothetical_gene_percentile)
    possibly_none_quantile = (
        gene_location.data["Gene End (bp)"] - gene_location.data["Gene Start (bp)"]
    ).quantile(hypothetical_gene_percentile / 100.0)
    if possibly_none_quantile is None:
        raise Exception(
            "Sequence gap calculation failed: quantile calculation returned None."
            + " Check HypoGenePercentile"
        )
    gene_length_hypothetical_minimum = math.ceil(possibly_none_quantile)
    log.debug(
        "Hypothetical genes to be inserted in gaps larger than %d",
        gene_length_hypothetical_minimum,
    )
    return gene_length_hypothetical_minimum


