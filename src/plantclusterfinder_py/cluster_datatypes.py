class Conversion(BaseModel):
    model_config = {"arbitrary_types_allowed": True}
    df: pl.DataFrame
    _cache: dict[Any, Any] = dict()

    @property
    def MapG(self) -> set[str]:
        if "MapG" in self._cache:
            return self._cache["MapG"]
        """Unique list of gene IDs stored in coversion file"""
        self._cache["MapG"] = set(self.df.get_column("Gene Name").unique())
        return self._cache["MapG"]

    @property
    def MapT(self) -> set[str]:
        if "MapT" in self._cache:
            return self._cache["MapT"]
        """Unique list of transcript IDs stored in coversion file"""
        self._cache["MapT"] = set(self.df.get_column("Transcript Name").unique())
        return self._cache["MapT"]

    @property
    def MapP(self) -> set[str]:
        if "MapP" in self._cache:
            return self._cache["MapP"]
        """Unique list of protein IDs stored in conversion file"""
        self._cache["MapP"] = set(self.df.get_column("Protein Name").unique())
        return self._cache["MapP"]

    @property
    def MapG_MapT(self) -> dict:
        if "MapG_MapT" in self._cache:
            return self._cache["MapG_MapT"]
        """Mapping between MapG and MapT"""
        self._cache["MapG_MapT"] = self.df.select(
            pl.col("Gene Name"), pl.col("Transcript Name")
        ).rows_by_key(key="Gene Name")
        return self._cache["MapG_MapT"]

    @property
    def MapG_MapP(self) -> dict:
        if "MapG_MapP" in self._cache:
            return self._cache["MapG_MapP"]
        """Mapping between MapG and MapP"""
        # TODO: Validate this is 1:1
        self._cache["MapG_MapP"] = self.df.select(
            pl.col("Gene Name"), pl.col("Protein Name")
        ).rows_by_key(key="Gene Name")
        return self._cache["MapG_MapP"]

    @property
    def MapP_MapG(self) -> dict:
        if "MapP_MapG" in self._cache:
            return self._cache["MapP_MapG"]
        """Mapping between MapG and MapP"""
        # TODO: Validate this is 1:1
        self._cache["MapP_MapG"] = self.df.select(
            pl.col("Gene Name"), pl.col("Protein Name")
        ).rows_by_key(key="Protein Name")
        return self._cache["MapP_MapG"]


class Clusters(BaseModel):
    model_config = {"arbitrary_types_allowed": True}
    # cluster information, stepsize, chromosome ID, gene start, gene end, number of enzymes, number of non-enzymes, and number of hypothetical genes
    ClusterMeta: pl.DataFrame
    """DataFrame with clustter information
        - stepsize
        - chromosome ID
        - gene start
        - gene end
        - number of enzymes
        - number of non-enzymes
        - number of hypothetical genes
        - top_cluster (if perform_cutoff is run)"""
    ClusterBackground: pl.DataFrame  # Density information about the genome
    """Density information about the genome
        - window size
        - number of enzymes
        - occurence of windowsize in genome
        - frequency of seeing a windowsize of this size with at least as many enzymes in the genome"""
    FinalStepSize: int
    """step size chosen by criterion"""
    MaxStepSize: int
    """maximal step size computed"""

    def perform_cutoff(self, vTopPercentClusters: int) -> List[bool]:
        """
        ---------------------------------------------------------------------------

        Function that (given clusters and a background density information of a
        genome) calculates whether the clusters are within the top n% of enzymes
        dense clusters.

        ---------------------------------------------------------------------------

        Args:
            clusters: Cluster Information (stepsize, chromosome id, gene start,
                    gene end, number of enzymes) and
                    Density information about the genome (window size,
                    number of enzymes, Occurrence of windowsize with
                    this many enzymes in the genome, occurence of
                    this windowsize in the genome, Frequency of seeing
                    a windowsize of this size with at least as many
                    enzymes in the genome)
            vTopPercentClusters: Clusters are labeled as being in the top n% if
                                they are within this top n% of enzyme dense
                                clusters compared to the background.

        Returns:
            List with size Number of Clusters. It is zero if
                the density of the cluster is above or the same as given
                by the input argument vTopPercentClusters*100.
        """
        log.debug(f"Perform cutoff for clusters in the top {vTopPercentClusters}%")
        cluster_meta_in_top = self.ClusterMeta.join(
            self.ClusterBackground.with_row_index("cluster_index"),
            left_on=["step_size", "enzyme_count"],
            right_on=["window_size", "enzyme_count"],
        ).select(
            pl.col("cluster_index"),
            top_percent_clusters=pl.col("winzyme_frequency")
            >= vTopPercentClusters / 100,
        )
        self.ClusterMeta = self.ClusterMeta.with_row_index("cluster_index").join(
            cluster_meta_in_top, "cluster_index", how="left"
        )

        return cluster_meta_in_top["top_percent_clusters"].to_list()
